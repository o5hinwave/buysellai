    func testAcceptanceDocsRouteNoSignArchiveThroughLocalVerifier() throws {
        let readme = try String(contentsOf: projectURL("README.md"), encoding: .utf8)
        let m10 = try String(contentsOf: projectURL("M10_ACCEPTANCE.md"), encoding: .utf8)

        XCTAssertNotNil(readme.range(of: "Scripts/verify_m10_local_archive.sh"))
        XCTAssertNotNil(readme.range(of: "M10_LOCAL_ARCHIVE_SNAPSHOT_ROOT=/tmp/buysell-m10-archive-worktree"))
        XCTAssertNotNil(m10.range(of: "Scripts/verify_m10_local_archive.sh"))
        XCTAssertNotNil(m10.range(of: "M10_LOCAL_ARCHIVE_SNAPSHOT_ROOT=/tmp/buysell-m10-archive-worktree"))
        XCTAssertNotNil(m10.range(of: "Binary-size check: archived app bundle stays under `20 MB`."))
        XCTAssertNotNil(m10.range(of: "App icon check: source App Store icon is a text-free camera-first 1024x1024 non-alpha PNG and the archive contains iPhone/iPad icon PNGs."))
        XCTAssertNotNil(m10.range(of: "Current-system design check: archived app omits `UIDesignRequiresCompatibility`."))
        XCTAssertNotNil(m10.range(of: "Custom font packaging check: archived app bundle contains no legacy custom font assets."))
        XCTAssertNotNil(m10.range(of: "Release fixture check: archived Release executable contains no UI-test sample fixture markers"))
